CREATE TABLE library_visits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  borrower_id BIGINT NOT NULL,
  checked_in_at TIMESTAMP NOT NULL,
  purpose VARCHAR(40) NOT NULL,
  entry_method VARCHAR(20) NOT NULL,
  CONSTRAINT fk_visit_borrower FOREIGN KEY (borrower_id) REFERENCES borrowers(id)
);
CREATE INDEX idx_visit_borrower_time ON library_visits(borrower_id, checked_in_at);
CREATE INDEX idx_visit_time ON library_visits(checked_in_at);

CREATE TABLE service_feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id BIGINT NOT NULL UNIQUE,
  rating VARCHAR(30) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_feedback_visit FOREIGN KEY (visit_id) REFERENCES library_visits(id)
);
CREATE INDEX idx_feedback_created ON service_feedback(created_at);
