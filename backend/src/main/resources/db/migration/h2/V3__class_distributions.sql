CREATE TABLE class_distributions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id BIGINT NOT NULL,
  grade_section VARCHAR(120) NOT NULL,
  school_year VARCHAR(20) NOT NULL,
  distributed_at TIMESTAMP NOT NULL,
  expected_return_date DATE NOT NULL,
  status VARCHAR(30) NOT NULL,
  notes VARCHAR(1000),
  created_by BIGINT NOT NULL,
  CONSTRAINT fk_distribution_teacher FOREIGN KEY (teacher_id) REFERENCES borrowers(id),
  CONSTRAINT fk_distribution_creator FOREIGN KEY (created_by) REFERENCES users(id)
);
ALTER TABLE loans ADD COLUMN distribution_id BIGINT;
ALTER TABLE loans ADD CONSTRAINT fk_loan_distribution FOREIGN KEY (distribution_id) REFERENCES class_distributions(id);
CREATE INDEX idx_distribution_teacher ON class_distributions(teacher_id);
CREATE INDEX idx_distribution_status ON class_distributions(status);
CREATE INDEX idx_distribution_school_year ON class_distributions(school_year);
CREATE INDEX idx_loan_distribution ON loans(distribution_id);
