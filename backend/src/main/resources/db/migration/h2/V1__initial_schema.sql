CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  school_id VARCHAR(80) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE borrowers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT UNIQUE,
  card_number VARCHAR(80) NOT NULL UNIQUE,
  grade_section VARCHAR(120),
  department VARCHAR(120),
  phone VARCHAR(40),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  notes VARCHAR(1000),
  CONSTRAINT fk_borrower_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(500) NOT NULL,
  subtitle VARCHAR(500),
  author VARCHAR(500),
  isbn VARCHAR(40),
  publisher VARCHAR(255),
  publication_year INTEGER,
  edition VARCHAR(100),
  subject VARCHAR(255),
  description VARCHAR(4000),
  cover_url VARCHAR(1000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE book_copies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL,
  accession_number VARCHAR(100) NOT NULL UNIQUE,
  call_number VARCHAR(100),
  volume_copy VARCHAR(100),
  pages VARCHAR(60),
  date_received DATE,
  source_of_fund VARCHAR(150),
  cost DECIMAL(12,2),
  status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
  remarks VARCHAR(1000),
  barcode VARCHAR(100) UNIQUE,
  CONSTRAINT fk_copy_book FOREIGN KEY (book_id) REFERENCES books(id)
);
CREATE TABLE loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  copy_id BIGINT NOT NULL,
  borrower_id BIGINT NOT NULL,
  borrowed_at TIMESTAMP NOT NULL,
  due_at TIMESTAMP NOT NULL,
  returned_at TIMESTAMP,
  notes VARCHAR(1000),
  checked_out_by BIGINT NOT NULL,
  returned_by BIGINT,
  CONSTRAINT fk_loan_copy FOREIGN KEY (copy_id) REFERENCES book_copies(id),
  CONSTRAINT fk_loan_borrower FOREIGN KEY (borrower_id) REFERENCES borrowers(id)
);
CREATE TABLE reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL,
  borrower_id BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_res_book FOREIGN KEY (book_id) REFERENCES books(id),
  CONSTRAINT fk_res_borrower FOREIGN KEY (borrower_id) REFERENCES borrowers(id)
);
CREATE TABLE acquisition_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id BIGINT NOT NULL,
  title VARCHAR(500) NOT NULL,
  author VARCHAR(500),
  reason VARCHAR(2000),
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_acq_user FOREIGN KEY (requester_id) REFERENCES users(id)
);
CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT,
  action VARCHAR(120) NOT NULL,
  entity_type VARCHAR(80) NOT NULL,
  entity_id VARCHAR(80),
  details VARCHAR(4000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE settings (
  setting_key VARCHAR(100) PRIMARY KEY,
  setting_value VARCHAR(2000) NOT NULL
);
CREATE INDEX idx_book_title ON books(title);
CREATE INDEX idx_copy_call ON book_copies(call_number);
CREATE INDEX idx_loan_borrower ON loans(borrower_id);
CREATE INDEX idx_loan_copy ON loans(copy_id);
