CREATE TABLE users (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL, first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', school_id VARCHAR(80) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE borrowers (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNIQUE,
  card_number VARCHAR(80) NOT NULL UNIQUE, grade_section VARCHAR(120),
  department VARCHAR(120), phone VARCHAR(40), status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  notes VARCHAR(1000), FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE books (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(500) NOT NULL, subtitle VARCHAR(500),
  author VARCHAR(500), isbn VARCHAR(40), publisher VARCHAR(255), publication_year INT,
  edition VARCHAR(100), subject VARCHAR(255), description TEXT, cover_url VARCHAR(1000),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_book_title(title(191))
) ENGINE=InnoDB;
CREATE TABLE book_copies (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, book_id BIGINT NOT NULL,
  accession_number VARCHAR(100) NOT NULL UNIQUE, call_number VARCHAR(100),
  volume_copy VARCHAR(100), pages VARCHAR(60), date_received DATE, source_of_fund VARCHAR(150),
  cost DECIMAL(12,2), status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
  remarks VARCHAR(1000), barcode VARCHAR(100) UNIQUE,
  FOREIGN KEY (book_id) REFERENCES books(id), INDEX idx_copy_call(call_number)
) ENGINE=InnoDB;
CREATE TABLE loans (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, copy_id BIGINT NOT NULL, borrower_id BIGINT NOT NULL,
  borrowed_at TIMESTAMP NOT NULL, due_at TIMESTAMP NOT NULL, returned_at TIMESTAMP NULL,
  notes VARCHAR(1000), checked_out_by BIGINT NOT NULL, returned_by BIGINT,
  FOREIGN KEY (copy_id) REFERENCES book_copies(id), FOREIGN KEY (borrower_id) REFERENCES borrowers(id),
  INDEX idx_loan_borrower(borrower_id), INDEX idx_loan_copy(copy_id)
) ENGINE=InnoDB;
CREATE TABLE reservations (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, book_id BIGINT NOT NULL, borrower_id BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING', requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (book_id) REFERENCES books(id), FOREIGN KEY (borrower_id) REFERENCES borrowers(id)
) ENGINE=InnoDB;
CREATE TABLE acquisition_requests (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, requester_id BIGINT NOT NULL, title VARCHAR(500) NOT NULL,
  author VARCHAR(500), reason TEXT, status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (requester_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE audit_logs (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT, action VARCHAR(120) NOT NULL,
  entity_type VARCHAR(80) NOT NULL, entity_id VARCHAR(80), details TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE settings (setting_key VARCHAR(100) PRIMARY KEY, setting_value TEXT NOT NULL) ENGINE=InnoDB;
